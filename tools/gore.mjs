import { chromium } from 'playwright';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto('http://localhost:5173/?autostart&nolock&diff=1');
await page.waitForFunction(() => window.__game && window.__game.time > 0.3, null, { timeout: 60000 });
const aim = (part) => page.evaluate((part) => {
  const g = window.__game; const P = g.player; g.godMode = true;
  const t = g.actors.find((a) => a.alive && !a.civilian && a.spawn.name === 'Merc (eating)');
  if (!t) return null;
  const h = t.pos.clone(); h.y += part === 'head' ? 1.64 : 1.2;
  const d = h.clone().sub(P.eyePos);
  P.yaw = Math.atan2(-d.x, -d.z); P.pitch = Math.atan2(d.y, Math.hypot(d.x, d.z));
  return t.id;
}, part);
await page.evaluate(() => { const g = window.__game; const P = g.player; P.give('ks12', 20); P.give('ar74', 60); P.equip('ks12', true); P.pos.set(-44, 0, 6.5); P.vel.set(0,0,0); });
await page.waitForTimeout(400);
await aim('head');
await page.mouse.down(); await page.waitForTimeout(50); await page.mouse.up();
await page.waitForTimeout(180);
await page.screenshot({ path: 'shots/40_shotgun_hit.png' });
await page.waitForTimeout(1600);
await page.screenshot({ path: 'shots/41_body.png' });
await page.evaluate(() => { const P = window.__game.player; P.equip('ar74', true); });
await page.waitForTimeout(300);
await aim('torso');
await page.mouse.down(); await page.waitForTimeout(500); await page.mouse.up();
await page.waitForTimeout(150);
await page.screenshot({ path: 'shots/42_rifle_burst.png' });
await page.waitForTimeout(2500);
await page.screenshot({ path: 'shots/43_after.png' });
const st = await page.evaluate(() => ({ ...window.__game.stats, pickups: window.__game.pickups.filter(p=>!p.taken).length }));
console.log(JSON.stringify(st));
console.log(errors.join('\n') || 'no errors');
await browser.close();
