import { chromium } from 'playwright';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto('http://localhost:5173/');
await page.waitForTimeout(800);
await page.screenshot({ path: 'shots/30_title.png' });
await page.click('#b-start'); await page.waitForTimeout(300);
await page.screenshot({ path: 'shots/31_missions.png' });
await page.click('.dossier[data-i="0"]'); await page.waitForTimeout(300);
await page.click('.diff[data-d="2"]'); await page.waitForTimeout(300);
await page.screenshot({ path: 'shots/32_difficulty.png' });
await page.click('#b-brief'); await page.waitForTimeout(300);
await page.screenshot({ path: 'shots/33_briefing.png' });
await page.click('#b-go'); await page.waitForSelector('#b-deploy', { timeout: 30000 });
await page.waitForTimeout(500);
await page.screenshot({ path: 'shots/34_deploy.png' });
console.log(errors.join('\n') || 'no errors');
await browser.close();
